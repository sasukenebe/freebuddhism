import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools/buddhist_canon_pipeline"))
import build_deploy_site as builder  # noqa: E402


class BuildSwapTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        self.build_root = self.root / "build"
        self.build_root.mkdir()
        self.destination = self.build_root / "site-root"
        self.staging = self.build_root / "staged"
        for path, text in ((self.destination, "old completed build"), (self.staging, "new validated build")):
            path.mkdir()
            (path / "index.html").write_text(text, encoding="utf-8")
        self.marker = self.build_root / ".site-root-managed"
        self.marker.write_text("Generated by default-deny build_deploy_site.py\n", encoding="utf-8")
        for name, value in (("ROOT", self.root), ("BUILD_ROOT", self.build_root),
                            ("WEBROOT", self.destination), ("BUILD_MARKER", self.marker),
                            ("READER_OUTPUT", self.build_root / "eligible-readers"),
                            ("READER_BUILDER", self.root / "tools/build_eligible_readers.py")):
            patcher = patch.object(builder, name, value)
            patcher.start()
            self.addCleanup(patcher.stop)
        self.backup, self.journal = builder._webroot_swap_paths()

    def text(self, path=None):
        return ((path or self.destination) / "index.html").read_text(encoding="utf-8")

    def test_success_installs_validated_build_before_removing_previous(self):
        original = builder.shutil.rmtree

        def remove(path):
            self.assertEqual(path, self.backup)
            self.assertEqual(self.text(), "new validated build")
            self.assertEqual(self.text(self.backup), "old completed build")
            return original(path)

        with patch.object(builder.shutil, "rmtree", side_effect=remove):
            builder.replace_webroot(self.staging, self.destination)
        self.assertEqual(self.text(), "new validated build")
        self.assertFalse(self.backup.exists())
        self.assertFalse(self.journal.exists())

    def test_first_or_second_rename_failure_preserves_the_old_build(self):
        original = Path.rename
        for fail_at in (self.destination, self.staging):
            with self.subTest(fail_at=fail_at):
                def rename(path, target):
                    if path == fail_at:
                        raise OSError("injected rename failure")
                    return original(path, target)
                with patch.object(Path, "rename", rename):
                    with self.assertRaisesRegex(OSError, "injected rename failure"):
                        builder.replace_webroot(self.staging, self.destination)
                self.assertEqual(self.text(), "old completed build")
                self.assertTrue(self.staging.is_dir())
                self.assertFalse(self.backup.exists())
                self.assertFalse(self.journal.exists())

    def test_failed_rollback_retains_backup_for_next_recovery(self):
        original = Path.rename

        def rename(path, target):
            if path in {self.staging, self.backup}:
                raise OSError("injected installation and recovery failure")
            return original(path, target)

        with patch.object(Path, "rename", rename):
            with self.assertRaisesRegex(OSError, "injected"):
                builder.replace_webroot(self.staging, self.destination)
        self.assertEqual(self.text(self.backup), "old completed build")
        self.assertTrue(self.journal.is_file())
        builder.recover_webroot_swap()
        self.assertEqual(self.text(), "old completed build")

    def test_cleanup_failure_keeps_new_build_and_recoverable_state(self):
        with patch.object(builder.shutil, "rmtree", side_effect=OSError("cleanup failure")):
            with self.assertRaisesRegex(OSError, "cleanup failure"):
                builder.replace_webroot(self.staging, self.destination)
        self.assertEqual(self.text(), "new validated build")
        self.assertEqual(self.text(self.backup), "old completed build")
        self.assertTrue(self.journal.exists())
        builder.recover_webroot_swap()
        self.assertEqual(self.text(), "new validated build")
        self.assertFalse(self.backup.exists())
        self.assertFalse(self.journal.exists())

    def test_recovery_before_move_and_after_cleanup_are_idempotent(self):
        builder._write_swap_journal(self.staging, self.journal)
        builder.recover_webroot_swap()
        builder.recover_webroot_swap()
        self.assertEqual(self.text(), "old completed build")
        builder._write_swap_journal(self.staging, self.journal)
        self.destination.rename(self.backup)
        self.staging.rename(self.destination)
        builder.shutil.rmtree(self.backup)
        builder.recover_webroot_swap()
        self.assertEqual(self.text(), "new validated build")
        self.assertFalse(self.journal.exists())

    def test_unowned_backup_changed_identity_and_bad_journal_fail_closed(self):
        self.backup.mkdir()
        with self.assertRaisesRegex(RuntimeError, "unowned website backup"):
            builder.recover_webroot_swap()
        self.backup.rmdir()
        builder._write_swap_journal(self.staging, self.journal)
        record = json.loads(self.journal.read_text())
        record["old"][1] += 1
        self.journal.write_text(json.dumps(record))
        with self.assertRaisesRegex(RuntimeError, "identities changed"):
            builder.recover_webroot_swap()
        self.journal.write_text("{}")
        with self.assertRaisesRegex(RuntimeError, "journal is malformed"):
            builder.recover_webroot_swap()
        self.assertEqual(self.text(), "old completed build")

    def test_symlinked_backup_or_journal_and_unmanaged_target_are_rejected(self):
        for path in (self.backup, self.journal):
            with self.subTest(path=path):
                path.symlink_to(self.staging)
                with self.assertRaisesRegex(RuntimeError, "symlink in the site output path"):
                    builder.recover_webroot_swap()
                path.unlink()
        self.marker.unlink()
        with self.assertRaisesRegex(RuntimeError, "unmanaged output directory"):
            builder.replace_webroot(self.staging, self.destination)
        self.assertEqual(self.text(), "old completed build")

    def test_concurrent_builds_are_rejected_and_lock_is_reusable(self):
        with builder.webroot_build_lock():
            with self.assertRaisesRegex(RuntimeError, "already running"):
                with builder.webroot_build_lock():
                    self.fail("second build acquired the lock")
        with builder.webroot_build_lock():
            pass

    def test_build_recovers_before_rendering_then_replaces_the_old_build(self):
        builder._write_swap_journal(self.staging, self.journal)
        self.destination.rename(self.backup)

        def render(*args, **kwargs):
            self.assertEqual(self.text(), "old completed build")
            self.assertFalse(self.backup.exists())

        def assemble(path):
            (path / "index.html").write_text("complete generated site", encoding="utf-8")
            return {"test": "validated"}

        with (patch.object(builder.subprocess, "run", side_effect=render) as command,
              patch.object(builder, "assemble_webroot", side_effect=assemble)):
            self.assertEqual(builder.build(), self.destination)
        command.assert_called_once()
        self.assertEqual(self.text(), "complete generated site")

    def test_assembly_failure_preserves_the_old_build_and_cleans_only_staging(self):
        with (patch.object(builder.subprocess, "run"),
              patch.object(builder, "assemble_webroot", side_effect=RuntimeError("assembly failed"))):
            with self.assertRaisesRegex(RuntimeError, "assembly failed"):
                builder.build()
        self.assertEqual(self.text(), "old completed build")
        self.assertEqual(list(self.build_root.glob(".site-root-*/")), [])
        self.assertFalse(self.backup.exists())
        self.assertFalse(self.journal.exists())

    def test_custom_preview_never_replaces_an_existing_directory(self):
        def assemble(path):
            (path / "index.html").write_text("custom preview", encoding="utf-8")
            return {}
        output = self.build_root / "preview"
        with (patch.object(builder.subprocess, "run"),
              patch.object(builder, "assemble_webroot", side_effect=assemble)):
            self.assertEqual(builder.build(output=output), output)
        self.assertEqual(self.text(output), "custom preview")
        with patch.object(builder.subprocess, "run") as command:
            with self.assertRaisesRegex(RuntimeError, "unmanaged output directory"):
                builder.build(output=output)
        command.assert_not_called()
        self.assertEqual(self.text(output), "custom preview")
        self.assertEqual(self.text(), "old completed build")

    def test_killed_process_between_renames_is_recovered_on_next_invocation(self):
        script = """
import os, signal, sys
from pathlib import Path
import build_deploy_site as b
b.ROOT = Path(sys.argv[1])
b.BUILD_ROOT = b.ROOT / 'build'
b.WEBROOT = b.BUILD_ROOT / 'site-root'
b.BUILD_MARKER = b.BUILD_ROOT / '.site-root-managed'
original = Path.rename
def rename(path, target):
    result = original(path, target)
    if path == (b.WEBROOT if sys.argv[2] == 'old' else b.BUILD_ROOT / 'staged'):
        os.kill(os.getpid(), signal.SIGKILL)
    return result
Path.rename = rename
with b.webroot_build_lock():
    b.replace_webroot(b.BUILD_ROOT / 'staged', b.WEBROOT)
"""
        environment = {**os.environ, "PYTHONPATH": str(ROOT / "tools/buddhist_canon_pipeline")}
        for stop_after in ("old", "new"):
            with self.subTest(stop_after=stop_after):
                result = subprocess.run([sys.executable, "-c", script, str(self.root), stop_after],
                                        env=environment, capture_output=True, text=True, timeout=30)
                self.assertEqual(result.returncode, -signal.SIGKILL, result.stderr)
                self.assertEqual(self.destination.exists(), stop_after == "new")
                self.assertEqual(self.text(self.backup), "old completed build")
                with builder.webroot_build_lock():
                    builder.recover_webroot_swap()
                expected = "old completed build" if stop_after == "old" else "new validated build"
                self.assertEqual(self.text(), expected)


if __name__ == "__main__":
    unittest.main()
